"""Deterministic addon-owned fixture generation. Never starts native tools."""
import argparse
import hashlib
import json
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def canon(data):
    return json.dumps(data, sort_keys=True, separators=(",", ":")).encode()

def quote(value):
    return json.dumps(value, ensure_ascii=True)

def vec(value):
    return quote(" ".join(str(x) for x in value))

def freeze_source(root):
    if not root.is_dir():
        raise ValueError(f"Shared runtime addon missing: {root}")
    files = {p.relative_to(root).as_posix(): digest(p) for p in sorted(root.rglob("*"))
             if p.is_file() and not any(part in (".git", ".cache") for part in p.parts)}
    if not files or "Gepard.gproj" not in files:
        raise ValueError("Shared source closure does not contain Gepard.gproj")
    return {"root": str(root), "sha256": hashlib.sha256(canon(files)).hexdigest(), "files": files}

def resource_file(root, resource):
    clean = re.sub(r"^\{[0-9a-fA-F]{16}\}", "", resource).replace("\\", "/")
    path = (root / clean).resolve()
    if not path.is_relative_to(root.resolve()):
        raise ValueError("Resource escapes source root")
    if not path.is_file():
        raise ValueError(f"Missing bound resource: {path}")
    if "{" in resource:
        meta = path.with_name(path.name + ".meta")
        if not meta.is_file() or resource.split("}")[0][1:].lower() not in meta.read_text().lower():
            raise ValueError(f"GUID does not match metadata: {resource}")
    return path

def generate():
    stations = json.loads((ROOT / "registry/stations.json").read_text())
    variants = json.loads((ROOT / "registry/variants.json").read_text())
    resources = json.loads((ROOT / "registry/resources.json").read_text())
    shared = freeze_source(Path(variants["sharedRuntime"]["sourceRoot"]))
    registry_hash = hashlib.sha256(canon([stations, variants, resources])).hexdigest()
    locked = []
    ids = set()
    for slot in variants["slots"]:
        if slot["id"] in ids:
            raise ValueError("Duplicate slot id")
        ids.add(slot["id"])
        item = dict(slot)
        if item["prefab"]:
            item["prefabSha256"] = digest(resource_file(Path(shared["root"]), item["prefab"]))
        else:
            item["prefabSha256"] = None
        locked.append(item)
    (ROOT / "checks").mkdir(exist_ok=True)
    lock = {"schema": 1, "registrySha256": registry_hash, "sharedRuntime": shared,
            "comparisonScope": variants["comparisonScope"], "slots": locked,
            "nativeStatus": "NOT_TESTED", "unboundSlots": [s["id"] for s in locked if not s["prefab"]]}
    (ROOT / "checks/variant-lock.json").write_text(json.dumps(lock, indent=2) + "\n")
    methods = []
    for key, resource in resources.items():
        methods.append(f' static ResourceName {key[0].upper()+key[1:]}() {{return {quote(resource)};}}')
    (ROOT / "addon/scripts/Game/GPG_Resources.c").write_text(
        "// Generated from registry/resources.json. Native assets referenced in place.\n"
        "class GPG_Resources\n{\n" + "\n".join(methods) + "\n}\n")
    source = ["// Generated by tools/generate.py. Do not hand edit.", "class GPG_Layout", "{",
              f' static string RegistryHash() {{return "{registry_hash}";}}',
              f' static string RuntimeHash() {{return "{shared["sha256"]}";}}',
              ' static ResourceName DamagePrefab() {return ' + quote(next(s["prefab"] for s in locked if s["id"] == variants["damageSubjectSlot"])) + ';}',
              ' static string Identities(string station)', ' {', '  if(station!="bay")return "";',
              '  return ' + quote("\n" + "\n".join(
                  f'{s["id"]}: {s["label"]}; prefab SHA256 {(s["prefabSha256"] or "UNBOUND")[:16]}' for s in locked)
                  + f'\nShared script/resource closure SHA256 {shared["sha256"][:16]}; full hashes in checks/variant-lock.json.') + ';',
              ' }', ' static void Build(GPG_Director world)', ' {']
    range_station=next(s for s in stations["stations"] if s["id"]=="range")
    source.insert(-2, ' static vector RangeLine() {return '+vec(range_station['position'])+';}')
    gate_yaws={g['id']:g.get('yaw',0) for g in stations['route']}
    gate_yaws.update({'RANGE FIRE EAST':90,'DAMAGE FIRE EAST':90,'DAMAGE FIRE NORTH':0})
    yaw_source=[' static float GateYaw(string id) {']
    yaw_source += ['  if(id=='+quote(i)+')return '+str(y)+';' for i,y in gate_yaws.items()]
    yaw_source += ['  return 0;',' }']
    source[-2:-2]=yaw_source
    for station in stations["stations"]:
        source.append('  world.Station(' + ",".join([quote(station["id"]), quote(station["title"]), quote(station["instructions"]), vec(station["position"]), vec(station["board"])]) + ');')
    for slot in locked:
        if slot["prefab"]:
            source.append('  world.Add(' + ','.join([quote(slot["id"]), '"bay"', quote(slot["prefab"]), vec(slot["position"])]) + ');')
        source.append('  world.Station(' + ','.join([quote("pad-" + slot["id"]), quote(slot["id"]), quote(slot["label"] + "; resource " + (slot["prefab"] or "UNBOUND") + "; prefab SHA256 " + (slot["prefabSha256"] or "UNBOUND") + "; shared closure " + shared["sha256"]), vec(slot["position"]), vec([slot["position"][0]-8,0,slot["position"][2]-3])]) + ');')
    for gate in stations["route"]:
        source.append(f'  world.Gate({quote(gate["id"])},{vec(gate["position"])});')
        x, y, z = gate["position"]
        source.append(f'  world.Station({quote(gate["id"])},{quote(gate["id"])},{quote(gate["kind"] + "; grade/material require native survey.")},{vec(gate["position"])},{vec([x-10,y,z])});')
    route_slot=next(s for s in locked if s['id']==variants['routeSubjectSlot'])
    if route_slot['prefab']:
        source.append(f'  world.Add("ROUTE-SUBJECT","drive",{quote(route_slot["prefab"])},{vec(stations["layoutPlanning"]["routeSubject"])},{stations["layoutPlanning"]["routeYaw"]});')
    audio=stations['layoutPlanning']['audioOrigin']
    for distance in (5,30,100):
        listener=[audio[0]-distance,0,audio[2]]
        board=[listener[0],0,listener[2]-5]
        source.append('  world.Station('+','.join([quote('AUDIO-'+str(distance)+'m'),quote('LISTENER '+str(distance)+'m horizontal'),quote('Stand WEST behind route start650/2695. Use one listening test at a time, stay clear of the moving route and record actual distance.'),vec(listener),vec(board)])+');')
    source.append('  world.Gate("RANGE FIRE EAST",'+vec(range_station['position'])+');')
    for target in stations["targets"]:
        resource = resources["infantryTarget" if target["kind"] == "infantry" else "vehicleTarget"]
        x,y,z = target["position"]
        actual = math.hypot(x-range_station["position"][0],z-range_station["position"][2])
        if abs(actual-target["distance"]) > .1:
            raise ValueError(f'Target distance mismatch {target["id"]}: {actual}')
        source.append(f'  world.Target({quote(target["id"])},{vec(target["position"])},{quote(resource)},{target["distance"]});')
        source.append('  world.Station(' + ','.join([quote(target['id']),quote(target['id']+' / '+str(target['distance'])+'m horizontal'),quote('Non-explosive range target. Actual slant distance/terrain visibility are in GPG_SURVEY. Fire only from the east-facing main line; reset at station04.'),vec(target['position']),vec([x,0,z+8])]) + ');')
    # Physical blast-cover cell: only a candidate enclosure until native review.
    for side in (-1,1):
        for offset in (-16,0,16):
            source.append(f'  world.Spawn(GPG_Resources.BlastCover(),"{1800+offset} 0 {1400+side*24}",0);')
            source.append(f'  world.Spawn(GPG_Resources.BlastCover(),"{1800+side*24} 0 {1400+offset}",90);')
    source += [' }','}']
    (ROOT / "addon/scripts/Game/GPG_Layout.c").write_text("\n".join(source) + "\n")
    coverage = {s["id"]:{"assertions":s["coverage"], "status":"NOT_TESTED", "reset":s["reset"]} for s in stations["stations"]}
    (ROOT / "checks/coverage.json").write_text(json.dumps(coverage,indent=2)+"\n")
    return lock

def verify(lock):
    # Meaningful source checks only. Not an Enforce parser or native compile.
    stations = json.loads((ROOT / "registry/stations.json").read_text())
    damage = next(s for s in stations["stations"] if s["id"] == "damage")
    bay = next(s for s in stations["stations"] if s["id"] == "bay")
    separation = math.dist(damage["position"],bay["position"])
    # Static planning corridors only; no blast/projectile containment inference.
    protected=[s['position'] for s in stations['stations'] if s['id'] in ('bay','service','range')]
    protected += [g['position'] for g in stations['route']]
    protected += [t['position'] for t in stations['targets']]
    protected += [s['position'] for s in lock['slots'] if s['prefab']]
    for corridor in stations['layoutPlanning']['damageCorridors']:
        a,b=corridor['start'],corridor['end'];w=corridor['halfWidth']
        for point in protected:
            assert not(min(a[0],b[0])-w<=point[0]<=max(a[0],b[0])+w and min(a[1],b[1])-w<=point[2]<=max(a[1],b[1])+w),'Protected station/pad intersects declared damage planning corridor'
    assert stations['layoutPlanning']['concurrency']=='DAMAGE_EXCLUSIVE_NO_OTHER_STATION_ACTIVITY'
    source = (ROOT / "addon/scripts/Game/GPG_Director.c").read_text()
    prohibited = ("SetHealth", "SetFuel(", "SetAmmoCount", "SetVelocity", "SetAngularVelocity", "SetThrottle", "SetBrake")
    assert not any(call in source for call in prohibited)
    assert "GPG-hostiles-qualified.flag" in source and "Backstop()" in source
    assert "Occupied(item.Entity)" in source and "GetVelocity().Length()>0.25" in source
    report = {"status":"PASS_SOURCE_CHECKS_ONLY", "nativeStatus":"NOT_TESTED", "damageBaySeparationMetres":separation,
              "targetHorizontalDistances":"PASS", "damageCorridorSourceNonintersection":"PASS_STATIC_ONLY_NOT_CONTAINMENT", "subjectMutationSettersAbsent":True,
              "hostileQualificationGate":True, "slotsBound":sum(bool(s["prefab"]) for s in lock["slots"]),
              "unboundSlots":lock["unboundSlots"], "nativeBlocker":"Source checks do not qualify native behavior; consult coordinator runtime lease and evidence"}
    (ROOT / "checks/source-checks.json").write_text(json.dumps(report,indent=2)+"\n")
    manifest = {p.relative_to(ROOT).as_posix():digest(p) for p in sorted((ROOT / "addon").rglob("*")) if p.is_file() and p.name!='resourceDatabase.rdb'}
    (ROOT / "checks/world-source-manifest.json").write_text(json.dumps({"sha256":hashlib.sha256(canon(manifest)).hexdigest(),"files":manifest},indent=2)+"\n")
    print(json.dumps(report))

def verify_frozen():
    lock=json.loads((ROOT/'checks/variant-lock.json').read_text())
    registry=[json.loads((ROOT/('registry/'+name+'.json')).read_text()) for name in ('stations','variants','resources')]
    if hashlib.sha256(canon(registry)).hexdigest()!=lock['registrySha256']:
        raise ValueError('FAIL: registry changed since freeze; review and regenerate')
    variants=registry[1]
    if Path(variants['sharedRuntime']['sourceRoot']).resolve()!=Path(lock['sharedRuntime']['root']).resolve():
        raise ValueError('FAIL: shared runtime root differs from frozen registry')
    actual=freeze_source(Path(lock['sharedRuntime']['root']))
    if actual['files']!=lock['sharedRuntime']['files'] or actual['sha256']!=lock['sharedRuntime']['sha256']:
        raise ValueError('FAIL: shared runtime closure changed; review and regenerate')
    pinned=json.loads((ROOT/'checks/world-source-manifest.json').read_text())
    if hashlib.sha256(canon(pinned['files'])).hexdigest()!=pinned['sha256']:
        raise ValueError('FAIL: world source manifest aggregate differs')
    current={p.relative_to(ROOT).as_posix():digest(p) for p in sorted((ROOT/'addon').rglob('*')) if p.is_file() and p.name!='resourceDatabase.rdb'}
    if current!=pinned['files']:
        raise ValueError('FAIL: world source changed since lock')
    return lock


if __name__ == "__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check",action="store_true")
    parser.add_argument("--verify-lock",action="store_true",help="read only; refuse changes since the last generated lock")
    args=parser.parse_args()
    if args.verify_lock:
        verify_frozen()
        print('PASS_FROZEN_SOURCE_ONLY; native compile/gameplay remains NOT_TESTED')
        raise SystemExit(0)
    lock=generate()
    if args.check:verify(lock)
